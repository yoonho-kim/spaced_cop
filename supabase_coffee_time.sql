drop policy if exists "app_coffee_time_members_write_authenticated" on app_coffee_time_members;
drop policy if exists "app_coffee_time_members_read_all" on app_coffee_time_members;
drop policy if exists "app_coffee_time_members_write_all" on app_coffee_time_members;
drop policy if exists "app_coffee_time_groups_read_authenticated" on app_coffee_time_groups;
drop policy if exists "app_coffee_time_groups_write_authenticated" on app_coffee_time_groups;
drop policy if exists "app_coffee_time_groups_read_all" on app_coffee_time_groups;
drop policy if exists "app_coffee_time_groups_write_all" on app_coffee_time_groups;
drop policy if exists "app_coffee_time_group_members_read_authenticated" on app_coffee_time_group_members;
drop policy if exists "app_coffee_time_group_members_write_authenticated" on app_coffee_time_group_members;
drop policy if exists "app_coffee_time_group_members_read_all" on app_coffee_time_group_members;
